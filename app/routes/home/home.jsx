export const meta = () => {
  return baseMeta({
    title: 'Software Engineer | AI/ML & ERP Systems',
    description: `Portfolio of ${config.name} — Software Engineer specializing in AI/ML, Microservices, and Enterprise Systems.`,
  });
};

export const Home = () => {
  const [visibleSections, setVisibleSections] = useState([]);
  const [scrollIndicatorHidden, setScrollIndicatorHidden] = useState(false);
  const intro = useRef();
  const projectOne = useRef();
  const projectTwo = useRef();
  const projectThree = useRef();
  const details = useRef();

  useEffect(() => {
    const sections = [
      intro,
      projectOne,
      projectTwo,
      projectThree,
      details,
    ];

    const sectionObserver = new IntersectionObserver(
      (entries, observer) => {
        entries.forEach(entry => {
          if (entry.isIntersecting) {
            const section = entry.target;
            observer.unobserve(section);
            if (visibleSections.includes(section)) return;
            setVisibleSections(prevSections => [...prevSections, section]);
          }
        });
      },
      { rootMargin: '0px 0px -10% 0px', threshold: 0.1 }
    );

    const indicatorObserver = new IntersectionObserver(
      ([entry]) => {
        setScrollIndicatorHidden(!entry.isIntersecting);
      },
      { rootMargin: '-100% 0px 0px 0px' }
    );

    sections.forEach(section => {
      if (section.current) {
        sectionObserver.observe(section.current);
      }
    });

    if (intro.current) {
      indicatorObserver.observe(intro.current);
    }

    return () => {
      sectionObserver.disconnect();
      indicatorObserver.disconnect();
    };
  }, [visibleSections]);

  return (
    <div className={styles.home}>
      <Intro
        id="intro"
        sectionRef={intro}
        scrollIndicatorHidden={scrollIndicatorHidden}
      />
      <ProjectSummary
        id="project-1"
        sectionRef={projectOne}
        visible={visibleSections.includes(projectOne.current)}
        index={1}
        title="Multi-Service Enterprise ERP Platform"
        description="Architected a modular microservices ERP integrating IAM service, partner/vendor portals, HRMS, and real-time inventory operations with Node.js, Express, React, PostgreSQL & Prisma."
        buttonText="View Details"
        buttonLink="/projects/enterprise-erp"
        model={{
          type: 'laptop',
          alt: 'Enterprise ERP Platform Dashboard',
          textures: [
            {
              srcSet: `${p1} 1280w`,
              placeholder: sprTexturePlaceholder,
            },
          ],
        }}
      />
      <ProjectSummary
        id="project-2"
        alternate
        sectionRef={projectTwo}
        visible={visibleSections.includes(projectTwo.current)}
        index={2}
        title="goovahaan — Vehicle Care & Garage Platform"
        description="Modular automotive platform connecting vehicle owners, garages, and service providers featuring NestJS microservices, Flutter cross-platform mobile app, and geospatial searches."
        buttonText="View Details"
        buttonLink="/projects/goovahaan"
        model={{
          type: 'phone',
          alt: 'goovahaan Mobile App interface',
          textures: [
            {
              srcSet: `${gamestackTexture} 375w, ${gamestackTextureLarge} 750w`,
              placeholder: gamestackTexturePlaceholder,
            },
            {
              srcSet: `${gamestackTexture2} 375w, ${gamestackTexture2Large} 750w`,
              placeholder: gamestackTexture2Placeholder,
            },
          ],
        }}
      />
      <ProjectSummary
        id="project-3"
        sectionRef={projectThree}
        visible={visibleSections.includes(projectThree.current)}
        index={3}
        title="VillageKart Sales Management System (VSMS)"
        description="End-to-end sales & field operations platform for real-time field tracking, agent workflows, daily revenue monitoring, and automated performance analytics."
        buttonText="View Details"
        buttonLink="/projects/vsms"
        model={{
          type: 'laptop',
          alt: 'VillageKart VSMS Operations Platform',
          textures: [
            {
              srcSet: `${p2} 1280w`,
              placeholder: sliceTexturePlaceholder,
            },
          ],
        }}
      />
      <Profile
        sectionRef={details}
        visible={visibleSections.includes(details.current)}
        id="details"
      />
      <Footer />
    </div>
  );
};
